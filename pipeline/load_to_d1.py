"""
Load vendor + tender data into Cloudflare D1.

Usage:
  python pipeline/load_to_d1.py              # generates SQL files only
  python pipeline/load_to_d1.py --execute    # generates + runs wrangler d1 execute

Requirements:
  - wrangler installed + logged in (npm install -g wrangler && wrangler login)
  - wrangler.jsonc has correct database_id filled in
  - data/vendors_full.json exists (raw scrape output)
  - Optional: data/tenders_full.json for tender_awards table
"""

import json
import re  # noqa: F401 (used by fix_column_shift)
import shutil
import subprocess
import sys
from datetime import datetime, date
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "data"  # repo-root data/ folder
OUT      = DATA
DB_NAME  = "oman-sme-intel"
BATCH    = 50   # rows per INSERT statement (D1 handles ~100 safely)

# ── helpers ───────────────────────────────────────────────────────────────────

def q(val):
    """SQL-escape a value."""
    if val is None:
        return "NULL"
    s = str(val).replace("'", "''")
    return f"'{s}'"

def parse_date(val):
    if not val:
        return None
    for fmt in ["%d-%m-%Y, %H:%M:%S", "%d-%m-%Y %H:%M:%S", "%d-%m-%Y", "%d/%m/%Y", "%Y-%m-%d", "%d %b %Y"]:
        try:
            return datetime.strptime(val.strip(), fmt).date().isoformat()
        except (ValueError, AttributeError):
            continue
    return None

_DATE_BLOB_RE = re.compile(r'\d{2}[-/]\d{2}[-/]\d{4}')

def extract_latest_date(val):
    """Parse a single date or extract the latest from a concatenated multi-date blob."""
    if not val:
        return None
    result = parse_date(val)
    if result:
        return result
    candidates = [parse_date(m) for m in _DATE_BLOB_RE.findall(val)]
    valid = [d for d in candidates if d]
    return max(valid) if valid else None

def normalise_category(cat):
    """Take first category if \n-joined multi-registration."""
    if not cat:
        return cat
    return cat.split('\n')[0].strip()

def normalise_expiry(exp):
    """Take latest expiry if \n-joined multi-registration."""
    if not exp:
        return exp
    parts = [p.strip() for p in exp.split('\n') if p.strip()]
    return parts[-1] if parts else exp

_SHIFT_NUM = re.compile(r'^\d{6,}$')
_DATE_PAT  = re.compile(r'^\d{2}[-/]\d{2}[-/]\d{4}')

def fix_column_shift(v):
    """Fix vendor records where a phone/fax number landed in the category slot,
    pushing the real category into reg_expiry and real date into company_type."""
    cat    = (v.get('category') or '').strip()
    expiry = (v.get('reg_expiry') or '').strip()
    if _SHIFT_NUM.match(cat) and not _DATE_PAT.match(expiry):
        return {
            **v,
            'category':    expiry,
            'reg_expiry':  (v.get('company_type') or '').strip(),
            'company_type': None,
        }
    return v

def load_json(path):
    if not path.exists():
        print(f"  WARNING: {path} not found - skipping")
        return []
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return data if isinstance(data, list) else []


# ── vendors → oman_smes ───────────────────────────────────────────────────────

def generate_smes_sql(vendors):
    print(f"  Generating oman_smes inserts for {len(vendors)} vendors...")
    cols = [
        "company_name", "commercial_reg_no", "contact_phone", "governorate",
        "vendor_reg_expiry", "vendor_category", "company_type",
        "oia_code_match", "source", "enriched",
    ]
    col_str = ", ".join(cols)

    OIA_CATEGORIES = {
        "construction and maintenance", "information technology services",
        "consulting offices", "supply", "services",
        "pipeline network construction and drilling wells",
        "electromechanical and telecommunications contracting and maintenance",
        "construction of ports roads bridges railways dams and maintenance",
    }

    lines = [
        "-- oman_smes inserts (generated by load_to_d1.py)",
        f"-- {len(vendors)} vendors | {datetime.utcnow().isoformat()}",
        "",
    ]

    seen_cr = set()
    seen_name = set()
    rows_written = 0
    batch_rows = []

    def flush(batch):
        lines.append(f"INSERT OR IGNORE INTO oman_smes ({col_str}) VALUES")
        lines.append(",\n".join(f"  ({r})" for r in batch) + ";")
        lines.append("")

    for v in vendors:
        v        = fix_column_shift(v)
        name     = (v.get("company_name") or "").strip()
        if not name:
            continue
        cr       = (v.get("cr_number") or "").strip()
        if cr and cr in seen_cr:
            continue
        if cr:
            seen_cr.add(cr)
        else:
            # No CR: dedup by normalised name to prevent re-insert on repeated runs
            norm_name = name.upper().strip()
            if norm_name in seen_name:
                continue
            seen_name.add(norm_name)

        cat      = normalise_category(v.get("category") or "")
        exp      = normalise_expiry(v.get("reg_expiry") or "")
        exp_iso  = extract_latest_date(exp)
        _ct_raw  = (v.get("company_type") or "").strip()
        ctype    = _ct_raw if _ct_raw in {"SME", "Local", "International"} else ""
        tel      = (v.get("tel") or "").strip()
        addr     = (v.get("address") or "").strip()
        oia      = 1 if cat.lower() in OIA_CATEGORIES else 0

        row = ", ".join([
            q(name),
            q(cr or None),
            q(tel or None),
            q(addr[:100] if addr else None),
            q(exp_iso),
            q(cat or None),
            q(ctype or None),
            str(oia),
            q("tender_vendor_registry"),
            "0",
        ])
        batch_rows.append(row)
        rows_written += 1

        if len(batch_rows) >= BATCH:
            flush(batch_rows)
            batch_rows = []

    if batch_rows:
        flush(batch_rows)

    print(f"  {rows_written} rows written (deduped by CR)")
    return "\n".join(lines)


# ── tenders → tender_awards ───────────────────────────────────────────────────

def generate_tenders_sql(tenders):
    print(f"  Generating tender_awards inserts for {len(tenders)} tenders...")
    cols = [
        "company_name", "commercial_reg", "tender_ref", "tender_title",
        "award_value_omr", "award_date", "buyer_entity", "sector", "source_url",
    ]
    col_str = ", ".join(cols)

    lines = [
        "-- tender_awards inserts (generated by load_to_d1.py)",
        f"-- {len(tenders)} tenders | {datetime.utcnow().isoformat()}",
        "",
    ]

    batch_rows = []
    rows_written = 0

    def flush(batch):
        lines.append(f"INSERT OR IGNORE INTO tender_awards ({col_str}) VALUES")
        lines.append(",\n".join(f"  ({r})" for r in batch) + ";")
        lines.append("")

    for t in tenders:
        company   = (t.get("company_name") or t.get("vendor_name") or t.get("awarded_company") or "").strip()
        if not company:
            continue
        cr        = (t.get("cr_number") or t.get("commercial_reg") or "").strip()
        ref       = (t.get("tender_no") or t.get("tender_number") or "").strip()
        title     = (t.get("tender_title") or "").strip()
        value     = t.get("awarded_value_omr") or t.get("award_value_omr")
        adate     = parse_date(t.get("awarded_date") or t.get("award_date") or "")
        entity    = (t.get("entity_name") or t.get("buyer_entity") or "").strip()
        sector    = (t.get("category_grade") or t.get("sector") or "").strip()
        url       = (t.get("opening_url") or "").strip()

        value_sql = str(float(value)) if value is not None else "NULL"

        row = ", ".join([
            q(company), q(cr or None), q(ref or None), q(title or None),
            value_sql, q(adate), q(entity or None), q(sector or None), q(url or None),
        ])
        batch_rows.append(row)
        rows_written += 1

        if len(batch_rows) >= BATCH:
            flush(batch_rows)
            batch_rows = []

    if batch_rows:
        flush(batch_rows)

    print(f"  {rows_written} rows written")
    return "\n".join(lines)


# ── wrangler execute ──────────────────────────────────────────────────────────

def run_wrangler(sql_file):
    print(f"\n  Running: wrangler d1 execute {DB_NAME} --file={sql_file} --remote")
    wrangler_cmd = shutil.which("wrangler") or "wrangler"
    cmd = f'"{wrangler_cmd}" d1 execute {DB_NAME} --file="{sql_file}" --remote'
    result = subprocess.run(
        cmd, shell=True, cwd=DATA.parent,  # run from repo root so wrangler finds wrangler.jsonc
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        encoding="utf-8", errors="replace",
    )
    out = ((result.stdout or "") + (result.stderr or "")).encode("ascii", "replace").decode("ascii")
    if result.returncode == 0:
        print(f"  OK: {out.strip()[:200]}")
    else:
        print(f"  ERROR: {out.strip()[:400]}")
    return result.returncode == 0


# ── main ──────────────────────────────────────────────────────────────────────

def main():
    execute = "--execute" in sys.argv
    OUT.mkdir(exist_ok=True)

    # Vendors
    vendors = load_json(DATA / "vendors_full.json")
    if vendors:
        sql = generate_smes_sql(vendors)
        out = OUT / "inserts_smes.sql"
        out.write_text(sql, encoding="utf-8")
        print(f"  -> {out} ({out.stat().st_size // 1024}KB)")
        if execute:
            run_wrangler(out)

    # Tenders (use enriched if available, else full)
    for fname in ["tenders_enriched.json", "tenders_full.json", "tenders_full.jsonl"]:
        tpath = DATA / fname
        if tpath.exists():
            if tpath.suffix == ".jsonl":
                tenders = [json.loads(l) for l in tpath.read_text(encoding="utf-8").splitlines() if l.strip()]
            else:
                tenders = load_json(tpath)
            if tenders:
                print(f"\nLoaded {len(tenders)} tenders from {fname}")
                sql = generate_tenders_sql(tenders)
                out = OUT / "inserts_tenders.sql"
                out.write_text(sql, encoding="utf-8")
                print(f"  -> {out} ({out.stat().st_size // 1024}KB)")
                if execute:
                    run_wrangler(out)
            break

    print("\nDone.")
    if not execute:
        print("\nNext steps:")
        print("  1. wrangler d1 create oman-sme-intel          # if not done yet")
        print("  2. # paste database_id into wrangler.jsonc")
        print("  3. wrangler d1 execute oman-sme-intel --file=schema.sql --remote")
        print("  4. python pipeline/load_to_d1.py --execute             # loads the data")

if __name__ == "__main__":
    main()
